"""Validation-side summary of the Experiment 1 replay and of Experiment 2. Reads no test data.

    python -m skeptic.analysis.validation_summary --decisions runs/decisions --out tables/validation_summary.md

Inputs: the replay decision files (runs/decisions/R{0,1,2}/ord_XXX.jsonl), runs/ledger.jsonl,
proposals/baselines.json and runs/exp2/summary.json. Sections marked "exploratory" are not in the
pre-registration; they describe validation behaviour only and make no claim about test.
"""
from __future__ import annotations

import argparse
import collections
import json
import math
from pathlib import Path

import numpy as np

CELLS = ("banking77_oos/bert", "banking77_oos/roberta", "clinc150/bert", "clinc150/roberta")
T_CRIT = 2.132          # one-sided 5% point of Student's t with 4 degrees of freedom (5 seeds)


def _rows(path):
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                yield json.loads(line)


def summarize(decisions, ledger_path="runs/ledger.jsonl", baselines_path="proposals/baselines.json") -> dict:
    auroc = {(r["sha"], r["cell"]): np.array(r["val"]["auroc"]) for r in _rows(ledger_path) if r["status"] == "ok"}
    named = json.loads(Path(baselines_path).read_text(encoding="utf-8"))
    names = {r["sha"]: r["name"] for r in (named["proposals"] if isinstance(named, dict) else named)}
    accepts = collections.defaultdict(list)
    distinct = collections.defaultdict(set)
    finals = collections.defaultdict(collections.Counter)
    verdicts = collections.defaultdict(collections.Counter)
    steps = collections.defaultdict(list)
    tests = collections.defaultdict(list)
    stream = collections.defaultdict(set)
    n_orderings = 0
    for rule in ("R0", "R1", "R2"):
        files = sorted(Path(decisions, rule).glob("ord_*.jsonl"))
        n_orderings = max(n_orderings, len(files))
        for path in files:
            per, last = collections.Counter(), {}
            for r in _rows(path):
                cell = r["cell"]
                stream[cell].add(r["sha"])
                if rule == "R2":
                    verdicts[cell][r["verdict"]] += 1
                    if r.get("p") is not None:
                        tests[cell].append((r["p"], r["alpha_t"], r["delta_val"], r["sha"]))
                if r["verdict"] == "ACCEPT":
                    per[cell] += 1
                    last[cell] = r["sha"]
                    distinct[(rule, cell)].add(r["sha"])
                    if rule == "R0":
                        d = auroc[(r["sha"], cell)] - auroc[(r["incumbent"], cell)]
                        sd = d.std(ddof=1)
                        steps[cell].append((d.mean(), int((d > 0).sum()), d.mean() / (sd / math.sqrt(len(d))) if sd > 0 else math.inf))
            for cell in CELLS:
                accepts[(rule, cell)].append(per[cell])
                finals[(rule, cell)][last.get(cell, "none")] += 1
    out = {"orderings": n_orderings, "cells": {}}
    for cell in CELLS:
        base = {names[s]: float(auroc[(s, cell)].mean()) for s in names if (s, cell) in auroc and names[s] != "vacuity@edl"}
        strongest = max(base, key=base.get)
        best = max(stream[cell], key=lambda s: auroc[(s, cell)].mean() if (s, cell) in auroc else -1)
        a = np.array(steps[cell])
        t = tests[cell]
        out["cells"][cell] = {
            "candidates": len(stream[cell]),
            "accepts": {rule: {"mean": float(np.mean(accepts[(rule, cell)])), "min": int(np.min(accepts[(rule, cell)])),
                               "max": int(np.max(accepts[(rule, cell)])), "distinct": len(distinct[(rule, cell)]),
                               "distinct_final_picks": len(finals[(rule, cell)])} for rule in ("R0", "R1", "R2")},
            "r2_verdicts": dict(verdicts[cell]),
            "energy_ce": base["energy@ce"], "strongest_baseline": strongest, "strongest_auroc": base[strongest],
            "best_candidate": best, "best_auroc": float(auroc[(best, cell)].mean()),
            "r0_steps": {"n": len(a), "median_gain": float(np.median(a[:, 0])), "share_below_0.001": float(np.mean(a[:, 0] < 0.001)),
                         "share_all_seeds": float(np.mean(a[:, 1] == len(auroc[(best, cell)]))),
                         "share_t_significant": float(np.mean(a[:, 2] > T_CRIT))},
            "g3": {"tests_per_ordering": len(t) / max(n_orderings, 1), "min_p": min(t)[0] if t else None,
                   "min_p_gain": min(t)[2] if t else None, "alpha_max": max(x[1] for x in t) if t else None,
                   "share_p_below_0.05": float(np.mean([x[0] < 0.05 for x in t])) if t else None},
        }
    return out


def markdown(s: dict, exp2_path="runs/exp2/summary.json") -> str:
    c = s["cells"]
    lines = ["# Validation-side results (no test data read)", "",
             f"Generated by `python -m skeptic.analysis.validation_summary` from the replay decisions ({s['orderings']} orderings per cell), "
             "`runs/ledger.jsonl` and `runs/exp2/summary.json`. The sealed test set was not opened; the registered test-side "
             "quantities (FDP, recall, winner's-curse gap, H1-H4) are **not computed**.", "",
             "## Experiment 1: proposals accepted per ordering (registered replay)", "",
             "| Cell | Candidates | R0 ratchet | R1 Thresholdout | R2 critic |", "|---|---|---|---|---|"]
    acc = lambda cell, rule: "{mean:.1f} [{min}-{max}]".format(**c[cell]["accepts"][rule])
    for cell in CELLS:
        lines.append(f"| {cell} | {c[cell]['candidates']} | {acc(cell, 'R0')} | {acc(cell, 'R1')} | {acc(cell, 'R2')} |")
    lines += ["", "Mean [min-max] over orderings. Harmonic-number reference: a random ordering of n items has about ln(n) + 0.58 "
              f"record-breakers ({math.log(c[CELLS[0]]['candidates']) + 0.5772:.1f} for n = {c[CELLS[0]]['candidates']}).", "",
              "## Experiment 1: critic verdicts (share of all R2 decisions)", "",
              "| Cell | SCORE-MATCHED | NO EFFECT | UNDERPOWERED | INERT | other | ACCEPT |", "|---|---|---|---|---|---|---|"]
    for cell in CELLS:
        v = c[cell]["r2_verdicts"]
        tot = sum(v.values())
        main = ("SCORE-MATCHED", "NO EFFECT", "UNDERPOWERED", "INERT")
        other = tot - sum(v.get(k, 0) for k in main) - v.get("ACCEPT", 0)
        lines.append(f"| {cell} | " + " | ".join(f"{100 * v.get(k, 0) / tot:.1f}%" for k in main)
                     + f" | {100 * other / tot:.1f}% | {v.get('ACCEPT', 0)} |")
    lines += ["", "## Exploratory: what the ratchet accepted (validation only)", "",
              "| Cell | Accepted steps | Median gain | Gain < 0.001 | Better in all 5 seeds | Seed-paired t, p < 0.05 | Distinct proposals ever accepted | Distinct final picks |",
              "|---|---|---|---|---|---|---|---|"]
    for cell in CELLS:
        r = c[cell]["r0_steps"]
        lines.append(f"| {cell} | {r['n']} | {r['median_gain']:.4f} | {100 * r['share_below_0.001']:.0f}% | {100 * r['share_all_seeds']:.0f}% | "
                     f"{100 * r['share_t_significant']:.0f}% | {c[cell]['accepts']['R0']['distinct']} | {c[cell]['accepts']['R0']['distinct_final_picks']} |")
    lines += ["", "## Exploratory: the best candidate against the strongest registered baseline (validation AUROC, seed mean)", "",
              "| Cell | CE energy | Strongest baseline | Best candidate | Gap | Smallest G3 p in the replay | Largest LORD++ level | G3 tests with p < 0.05 |",
              "|---|---|---|---|---|---|---|---|"]
    for cell in CELLS:
        x, g = c[cell], c[cell]["g3"]
        lines.append(f"| {cell} | {x['energy_ce']:.4f} | {x['strongest_baseline']} {x['strongest_auroc']:.4f} | `{x['best_candidate']}` {x['best_auroc']:.4f} | "
                     f"{x['best_auroc'] - x['strongest_auroc']:+.4f} | {g['min_p']:.4f} | {g['alpha_max']:.4f} | {100 * g['share_p_below_0.05']:.1f}% |")
    if Path(exp2_path).exists():
        runs = json.loads(Path(exp2_path).read_text(encoding="utf-8"))
        lines += ["", "## Experiment 2: closed loop, 3 runs x 80 proposal slots per arm and benchmark (BERT)", "",
                  "| Benchmark | Arm | Rule and memory | Judged | Accepted per run | Wasted share, slots 1-40 | Wasted share, slots 41-80 | Change (H5) |",
                  "|---|---|---|---|---|---|---|---|"]
        what = {"A": "ratchet, own history", "B": "critic, shared memory", "C": "critic, no memory"}
        for cell in sorted({r["cell"] for r in runs}):
            for arm in "ABC":
                rs = [r for r in runs if r["cell"] == cell and r["arm"] == arm]
                if rs:
                    m = lambda k: float(np.mean([r[k] for r in rs]))
                    lines.append(f"| {cell} | {arm} | {what[arm]} | {sum(r['judged'] for r in rs)} | {', '.join(str(r['accepted']) for r in rs)} | "
                                 f"{m('wasted_first_half'):.2f} | {m('wasted_second_half'):.2f} | {m('wasted_change'):+.2f} |")
        lines += ["", "H5 is descriptive. The wasted share rises to 0.94-1.00 in every arm: with about six families and a few verdicts, "
                  "nearly every (family, verdict) pair has occurred after 40 proposals, so the registered measure saturates and does not separate the arms."]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--decisions", default="runs/decisions")
    ap.add_argument("--ledger", default="runs/ledger.jsonl")
    ap.add_argument("--baselines", default="proposals/baselines.json")
    ap.add_argument("--exp2", default="runs/exp2/summary.json")
    ap.add_argument("--out", default="tables/validation_summary.md")
    args = ap.parse_args(argv)
    text = markdown(summarize(args.decisions, args.ledger, args.baselines), args.exp2)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
